"""Emit COLAB.md: the notebook cells, labelled, ready to paste into Colab.

Generated from nb/*.py so the markdown can never drift from the code that
actually runs. Re-run after editing anything in nb/.

    python make_colab_md.py
"""

from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).parent
NB = ROOT / "nb"

TITLE = """# DiffusionGemma prose eval - Colab cells

Paste each block into a Colab cell in order. Four cells.

Generated by `make_colab_md.py` from `nb/` - do not hand-edit.

| Cell | What | Needs weights? |
|---|---|---|
| 1 | install + landmine workarounds | no |
| 2 | verify install, print devices | no |
| 3 | write `metrics.py`, `prompts.py`, `generate.py` (3a-3c) | no |
| 4 | generate | **yes** - ~50 GB from `gs://gemma-data/` |

Cells 1-3 run on any runtime and load **zero** weights. Run those first; if
they pass, the environment is sound and cell 4 is where the real cost is.

Cells 1-3a/b/c are seven cells total - the cell numbering below is
1, 2, 3a, 3b, 3c, 4.
"""

LEAD = {
    1: """## Cell 1 - install

Three landmines, each of which fails the install outright. Validated in a
clean venv; the details are at the bottom of this file.
""",
    2: """## Cell 2 - verify (weightless)

Confirms jax sees the right backend and that `gemma.diffusion` actually
imported. If `diff ckpt` prints, the install is sound. Runs in seconds and
downloads nothing.
""",
    3: """## Cell 3 - write the harness files

Reuses the exact same `metrics.py` / `prompts.py` / `generate.py` that the
Kaggle kernels use, so results stay comparable across both platforms.

`%%writefile` applies to a whole cell, so each file needs its own cell -
3a, 3b, 3c. Run all three before cell 4.
""",
    4: """## Cell 4 - generate

First run downloads ~50 GB of weights from the public bucket. Budget 5-15 min.
The first `sampler.chat` JIT-compiles for another 1-2 min, once.

Set `MODEL` to `"diffusion"` or `"ar"`. Run it twice, once each, and never
both in one session - two 26B models is ~100 GB.
""",
}

NOTES = """---

## Notes on the three landmines

1. **PyPI `gemma` 4.0.1 has no `diffusion` module.** The Colab example
   notebook assumes `!pip install -q gemma` then `from gemma import diffusion`
   - that does not work on the current PyPI release. Git `main` is 4.1.0 and
   does have it, so install from git.

2. **`tensorflow-cpu` was removed from PyPI**, but `gemma` and `kauldron`
   both still pin it as a hard dependency. pip cannot resolve it
   (`No matching distribution found`). The fix is a three-line stub package
   that forwards to `tensorflow`, which is the real package now.

3. **kauldron imports `np.float128`**, removed in numpy 2. Hence `numpy<2`.
   (On Apple Silicon that attribute is missing even on numpy 1.x, since arm64
   has no extended-precision float - so this step is what lets the install
   *complete* on macOS, though importing kauldron there still needs a shim.
   On Colab/Kaggle Linux it works directly.)

## Verified separately

Checked against the installed `gemma` 4.1.0 source, not the docs:

- `diffusion.ChatSampler` subclasses `gm.text.ChatSampler` directly, so the
  "drop-in replacement" claim is structural rather than conventional.
- All 7 `diffusion.ChatSampler` kwargs used here are valid - `model`,
  `params`, `tokenizer`, `pad_length`, `max_out_length` are inherited;
  `canvas_length`, `max_denoising_steps` are its own.
- All 3 `gm.text.ChatSampler` kwargs are valid: `model`, `params`,
  `multi_turn`.
- `gm.ckpts.load_params` accepts `restore_concurrent_gb`, `text_only` and
  `quantize`. `text_only` and `quantize` are the lever for later if you ever
  need both towers resident at once.

## Local analysis (on your Mac, not in Colab)

```
python nb/analyze.py out/diffusion.jsonl out/ar.jsonl
```

Paired comparison with bootstrap 95% CIs, broken out per prompt category.
Then, with `GOOGLE_API_KEY` set:

```
python nb/judge.py out/diffusion.jsonl out/ar.jsonl
```

Blind pairwise judging, each pair judged twice with the order swapped; only
order-invariant verdicts are counted.
"""

CELL4 = '''import os
import pathlib
import subprocess
import sys

MODEL = "diffusion"          # <- "diffusion" or "ar"
OUT = pathlib.Path("/content/out")
OUT.mkdir(parents=True, exist_ok=True)
os.environ["XLA_PYTHON_CLIENT_PREALLOCATE"] = "false"

print("downloading/loading ~50 GB of weights, then JIT compiling...")
r = subprocess.run(
    [sys.executable, "/content/generate.py", "--model", MODEL,
     "--out", str(OUT / f"{MODEL}.jsonl")],
    capture_output=True, text=True)
print(r.stdout[-4000:])
if r.returncode:
    print("STDERR:", r.stderr[-4000:])

path = OUT / f"{MODEL}.jsonl"
if path.exists():
    import json
    rows = [json.loads(l) for l in path.read_text().splitlines() if l.strip()]
    ok = [x for x in rows if x.get("response")]
    mean = sum(x["metrics"].get("n_tokens", 0) for x in ok) / max(len(ok), 1)
    print(f"\\n{len(ok)}/{len(rows)} rows, mean {mean:.0f} tokens")
    print("sample:\\n", ok[0]["response"][:500] if ok else "(none)")
else:
    print("no output file")
'''


def fence(body: str) -> str:
    return f"```python\n{body.rstrip()}\n```\n"


def main() -> None:
    blocks = {
        1: (NB / "cell1_install.py").read_text().rstrip(),
        2: (NB / "cell2_verify.py").read_text().rstrip(),
        4: CELL4.rstrip(),
    }

    parts = [TITLE]
    for n in (1, 2):
        parts += ["---\n", LEAD[n], fence(blocks[n])]
    for label, name in (("3a", "metrics"), ("3b", "prompts"), ("3c", "generate")):
        lead = LEAD[3] if label == "3a" else ""
        parts += ["---\n", lead,
                  f"### Cell {label} - `%%writefile {name}.py`\n",
                  fence(f"%%writefile {name}.py\n"
                        + (NB / f"{name}.py").read_text().rstrip())]
    parts += ["---\n", LEAD[4], fence(blocks[4]), NOTES]

    md = "\n".join(parts)
    (ROOT / "COLAB.md").write_text(md)

    n_fence = md.count("```")
    assert n_fence % 2 == 0, f"unbalanced fences: {n_fence}"
    for n in (1, 2, 3, 4):
        assert f"## Cell {n} -" in md, f"missing heading for cell {n}"
    print(f"wrote {ROOT / 'COLAB.md'}  ({len(md):,} bytes, "
          f"{n_fence // 2} fenced blocks, 4 cells labelled)")


if __name__ == "__main__":
    main()
